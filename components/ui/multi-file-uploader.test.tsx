import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
import { StrictMode } from "react"
import { MultiFileUploader } from "./multi-file-uploader"
const upload = vi.fn(), validar = vi.fn(), exito = vi.fn()
const props = { maxFiles: 7, accept: "image/png", maxBytes: 100, instrucciones: "PNG", etiqueta: "Archivo", validar, upload, onSuccess: exito }
const file = (name: string) => new File(["png"], name, { type: "image/png" })
const input = () => screen.getByLabelText("Archivos para cargar", { selector: "input" })
beforeEach(() => {
  upload.mockReset(); validar.mockReset().mockResolvedValue(undefined); exito.mockReset()
  vi.stubGlobal("URL", class extends URL { static createObjectURL = vi.fn((f: File) => `blob:${f.name}`); static revokeObjectURL = vi.fn() })
})
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
it("captura un FileList vivo antes de limpiar el input, incluso con drag y StrictMode", async () => {
  render(<StrictMode><MultiFileUploader {...props} /></StrictMode>)
  let vivos = [file("A.png"), file("B.png")]
  const lista = { get length() { return vivos.length }, item: (n: number) => vivos[n], [Symbol.iterator]: () => vivos[Symbol.iterator]() }
  Object.defineProperty(input(), "value", { configurable: true, get: () => "", set: () => { vivos = [] } })
  act(() => {
    fireEvent.dragEnter(screen.getByRole("button", { name: "Agregar archivos" }))
    fireEvent.change(input(), { target: { files: lista } })
  })
  expect(vivos).toHaveLength(0)
  await screen.findByText("A.png"); await screen.findByText("B.png")
  expect(screen.getAllByRole("listitem")).toHaveLength(2)
  expect(upload).not.toHaveBeenCalled()
})
it("una seleccion nueva espera confirmacion incluso despues de completar otra tanda", async () => {
  upload.mockResolvedValue({ vista: { url: "https://example.test/A.png" }, resultado: "A" })
  render(<MultiFileUploader {...props} />)
  fireEvent.change(input(), { target: { files: [file("A.png")] } })
  await screen.findByText("Archivo seleccionado. Listo para subir.")
  await waitFor(() => expect((screen.getByRole("button", { name: "Subir archivos" }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole("button", { name: "Subir archivos" }))
  await waitFor(() => expect(exito).toHaveBeenCalledTimes(1))
  fireEvent.change(input(), { target: { files: [file("B.png")] } })
  await screen.findByText("Archivo seleccionado. Listo para subir.")
  expect(upload).toHaveBeenCalledTimes(1)
  expect(screen.getByText("B.png")).toBeTruthy()
})
it("elegir otro archivo en una fila comunica el File realmente enviado al confirmar", async () => {
  upload.mockResolvedValue({ vista: { url: "https://example.test/B.png" }, resultado: "B" })
  render(<MultiFileUploader {...props} />)
  fireEvent.change(input(), { target: { files: [file("A.png")] } })
  await screen.findByText("Archivo seleccionado. Listo para subir.")
  const b = file("B.png")
  fireEvent.change(screen.getByLabelText("Archivo: A.png"), { target: { files: [b] } })
  await screen.findByText("B.png")
  await waitFor(() => expect((screen.getByRole("button", { name: "Subir archivos" }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole("button", { name: "Subir archivos" }))
  await waitFor(() => expect(exito).toHaveBeenCalledWith("B", b))
})
it("multiple muestra todos, conserva identidad y rechaza toda seleccion que supera cupo", async () => {
  render(<MultiFileUploader {...props} count={5} />)
  fireEvent.change(input(), { target: { files: [file("A.png"), file("B.png")] } })
  expect(await screen.findByText("A.png")).toBeTruthy(); expect(await screen.findByText("B.png")).toBeTruthy()
  await waitFor(() => expect(screen.getAllByText("Archivo seleccionado. Listo para subir.")).toHaveLength(2))
  fireEvent.change(input(), { target: { files: [file("C.png")] } })
  expect(await screen.findByRole("alert")).toHaveProperty("textContent", expect.stringContaining("máximo de 7"))
  expect(screen.queryByText("C.png")).toBeNull(); expect(upload).not.toHaveBeenCalled()
})
it("cola serial, progreso independiente, fallo aislado y retry solo del mismo archivo", async () => {
  let terminar!: (r: unknown) => void, fallar!: (e: Error) => void
  upload.mockImplementation(() => new Promise((r, e) => { terminar = r; fallar = e }))
  render(<MultiFileUploader {...props} />)
  const a = file("A.png"), b = file("B.png")
  fireEvent.change(input(), { target: { files: [a, b] } })
  await waitFor(() => expect(screen.getAllByText("Archivo seleccionado. Listo para subir.")).toHaveLength(2))
  await waitFor(() => expect((screen.getByRole("button", { name: "Subir archivos" }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole("button", { name: "Subir archivos" }))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(1))
  await waitFor(() => expect((screen.getByRole("button", { name: "Subir archivos" }) as HTMLButtonElement).disabled).toBe(true))
  act(() => upload.mock.calls[0][1].alProgreso(44))
  expect(screen.getByRole("progressbar").getAttribute("value")).toBe("44")
  act(() => upload.mock.calls[0][1].alProcesar())
  expect(screen.getByRole("progressbar").hasAttribute("value")).toBe(false)
  await act(async () => fallar(new Error("Fallo de A")))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(2))
  expect(upload.mock.calls[1][0]).toBe(b); expect(screen.getByText("Fallo de A")).toBeTruthy()
  await act(async () => terminar({ vista: { url: "https://example.test/B.png" }, resultado: "B" }))
  expect(exito).toHaveBeenCalledWith("B", b)
  fireEvent.click(screen.getByRole("button", { name: "Reintentar" }))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(3))
  expect(upload.mock.calls[2][0]).toBe(a)
  expect(screen.getByText("Reintentando archivo…")).toBeTruthy()
  await act(async () => terminar({ vista: { url: "https://example.test/A.png" }, resultado: "A" }))
  expect(exito).toHaveBeenCalledWith("A", a)
  expect(URL.revokeObjectURL).toHaveBeenCalledWith("blob:A.png")
  expect(URL.revokeObjectURL).toHaveBeenCalledWith("blob:B.png")
})
it("drag, teclado y quitar invalido liberan cupo sin transferencia", async () => {
  validar.mockRejectedValue(new Error("Formato inválido"))
  render(<MultiFileUploader {...props} />)
  const zona = screen.getByRole("button", { name: "Agregar archivos" })
  zona.focus(); expect(document.activeElement).toBe(zona)
  const click = vi.spyOn(input(), "click").mockImplementation(() => {})
  fireEvent.keyDown(zona, { key: "Enter" }); fireEvent.keyDown(zona, { key: " " }); expect(click).toHaveBeenCalledTimes(2)
  fireEvent.dragEnter(zona); expect(screen.getByText("Soltá para agregar")).toBeTruthy()
  fireEvent.dragLeave(zona); expect(screen.queryByText("Soltá para agregar")).toBeNull()
  fireEvent.drop(zona, { dataTransfer: { files: [file("roto.png")] } })
  await screen.findByText("Formato inválido")
  expect(screen.getByText("roto.png")).toBeTruthy()
  expect(screen.getAllByRole("button", { name: /Agregar archivos|Seleccionar archivo para cargar/ })).toHaveLength(1)
  expect(screen.getAllByRole("button", { name: "Quitar archivo" })).toHaveLength(1)
  expect(screen.queryByRole("button", { name: "Reintentar" })).toBeNull()
  fireEvent.click(await screen.findByRole("button", { name: "Quitar archivo" }))
  expect(screen.queryByText("Formato inválido")).toBeNull(); expect(upload).not.toHaveBeenCalled()
  expect(URL.revokeObjectURL).toHaveBeenCalledWith("blob:roto.png")
})

it("auto-upload serial sin boton global: sumar durante carga, processing, retry y quitar no reenvian exitosos", async () => {
  let terminar!: (r: unknown) => void, fallar!: (e: Error) => void
  const cambios = vi.fn()
  upload.mockImplementation(() => new Promise((r, e) => { terminar = r; fallar = e }))
  render(<StrictMode><MultiFileUploader {...props} autoUpload alCambiarCola={cambios} /></StrictMode>)
  const a = file("auto-A.png"), b = file("auto-B.png"), c = file("auto-C.png")
  fireEvent.change(input(), { target: { files: [a, b] } })
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(1))
  expect(screen.queryByRole("button", { name: "Subir archivos" })).toBeNull()
  act(() => upload.mock.calls[0][1].alProgreso(45))
  expect(screen.getByText("Subiendo 45 %")).toBeTruthy()
  expect(screen.getByRole("progressbar").getAttribute("value")).toBe("45")
  fireEvent.change(input(), { target: { files: [c] } })
  expect(screen.getAllByText("Pendiente").length).toBeGreaterThan(0)
  act(() => upload.mock.calls[0][1].alProcesar())
  expect(screen.getByText("Procesando…")).toBeTruthy()
  expect(screen.getByRole("progressbar").hasAttribute("value")).toBe(false)
  await act(async () => terminar({ vista: { url: "https://example.test/A.png" }, resultado: "A" }))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(2))
  expect(upload.mock.calls[1][0]).toBe(b)
  await act(async () => terminar({ vista: { url: "https://example.test/B.png" }, resultado: "B" }))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(3))
  expect(upload.mock.calls[2][0]).toBe(c)
  await act(async () => fallar(new Error("Error de C")))
  expect(await screen.findByRole("alert")).toHaveProperty("textContent", "Error de C")
  expect(cambios).toHaveBeenLastCalledWith({ pendientes: 0, errores: 1 })
  fireEvent.click(screen.getByRole("button", { name: "Reintentar" }))
  await waitFor(() => expect(upload).toHaveBeenCalledTimes(4))
  expect(upload.mock.calls[3][0]).toBe(c)
  await act(async () => fallar(new Error("Error de C")))
  fireEvent.click(screen.getByRole("button", { name: "Quitar archivo" }))
  expect(cambios).toHaveBeenLastCalledWith({ pendientes: 0, errores: 0 })
  expect(exito).toHaveBeenCalledTimes(2)
  expect(upload.mock.calls.filter(call => call[0] === a)).toHaveLength(1)
  expect(upload.mock.calls.filter(call => call[0] === b)).toHaveLength(1)
})

it("auto-upload conserva orden de seleccion aunque el segundo archivo termine de validar antes", async () => {
  let validarPrimero!: () => void
  validar.mockImplementationOnce(() => new Promise<void>(r => { validarPrimero = r })).mockResolvedValue(undefined)
  upload.mockResolvedValue({ vista: { url: "https://example.test/guardado.png" }, resultado: "ok" })
  render(<MultiFileUploader {...props} autoUpload />)
  const a = file("orden-A.png"), b = file("orden-B.png")
  fireEvent.change(input(), { target: { files: [a, b] } })
  await screen.findByText("Pendiente")
  expect(upload).not.toHaveBeenCalled()
  await act(async () => validarPrimero())
  await waitFor(() => expect(exito).toHaveBeenCalledTimes(2))
  expect(upload.mock.calls.map(llamada => llamada[0])).toEqual([a, b])
})
