import { act, fireEvent, render, screen, waitFor, within } from "@testing-library/react"
import { beforeEach, expect, it, vi } from "vitest"
import { EgresosAdmin } from "./egresos-admin"
import type { EgresoDetalle } from "@/lib/modulos/egresos/contrato"

const { registrar, detalle, anular, refresh } = vi.hoisted(() => ({ registrar: vi.fn(), detalle: vi.fn(), anular: vi.fn(), refresh: vi.fn() }))
vi.mock("next/navigation", () => ({ useRouter: () => ({ refresh }) }))
vi.mock("@/app/admin/(panel)/egresos/acciones", () => ({ registrarEgresoAccion: registrar, detalleEgresoAccion: detalle, anularEgresoAccion: anular }))
const e: EgresoDetalle = { id: "a1111111-1111-4111-8111-111111111111", concepto: "Alquiler", importe: "1200.50", moneda: "ARS", fechaOperacion: "2026-11-10", nota: "Comprobante", estado: "CONFIRMADO", creadoEn: "2026-11-10T15:00:00Z", anuladoEn: null }
const filtros = { desde: "2026-11-01", hasta: "2026-11-30", estado: "" }
beforeEach(() => { registrar.mockReset(); detalle.mockReset(); anular.mockReset(); refresh.mockReset() })
const abrir = () => { render(<EgresosAdmin egresos={[]} filtros={filtros} />); fireEvent.click(screen.getByRole("button", { name: "Registrar gasto" })) }
const completar = () => {
  fireEvent.change(screen.getByLabelText("Concepto *"), { target: { value: "Alquiler" } })
  fireEvent.change(screen.getByLabelText("Importe (ARS) *"), { target: { value: "1200.50" } })
  fireEvent.change(screen.getByLabelText("Fecha de operación *"), { target: { value: "2026-11-10" } })
}
it("lista datos reales con filtros y sin acciones editar o borrar", () => {
  render(<EgresosAdmin egresos={[e]} filtros={filtros} />)
  expect(screen.getByRole("table", { name: "Gastos" })).toBeTruthy()
  expect(screen.getByText("Alquiler")).toBeTruthy()
  expect((screen.getByLabelText("Período") as HTMLSelectElement).value).toBe("fechas")
  expect(screen.queryByRole("button", { name: "Filtrar" })).toBeNull()
  expect((screen.getByLabelText("Desde") as HTMLInputElement).value).toBe("2026-11-01")
  expect(screen.queryByRole("button", { name: /Editar|Eliminar/ })).toBeNull()
})
it("vacio, error e invalidacion de filtros son distintos", () => {
  const { rerender } = render(<EgresosAdmin egresos={[]} filtros={filtros} />)
  expect(screen.getByText("No hay gastos en este período")).toBeTruthy()
  rerender(<EgresosAdmin egresos={[]} filtros={filtros} errorCarga />)
  expect(screen.getByRole("alert").textContent).toContain("No pudimos consultar")
  rerender(<EgresosAdmin egresos={[]} filtros={filtros} erroresFiltro={{ hasta: "Rango inválido" }} />)
  expect(screen.getByText("Rango inválido")).toBeTruthy()
  expect(screen.queryByText("No hay gastos en este período")).toBeNull()
})
it("error por campo conserva entradas y enfoca el campo", async () => {
  registrar.mockResolvedValue({ estado: "datos_invalidos", errores: { importe: "El importe debe ser mayor que cero." } })
  abrir(); completar()
  fireEvent.submit(screen.getByRole("form", { name: "Registrar gasto" }))
  const error = await screen.findByText("El importe debe ser mayor que cero.")
  const input = screen.getByLabelText("Importe (ARS) *")
  await waitFor(() => expect(document.activeElement).toBe(input))
  expect(input.getAttribute("aria-describedby")).toBe(error.id)
  expect((screen.getByLabelText("Concepto *") as HTMLInputElement).value).toBe("Alquiler")
  expect(refresh).not.toHaveBeenCalled()
})
it("retry conserva clave y no anuncia exito antes de respuesta", async () => {
  registrar.mockResolvedValueOnce({ estado: "error_tecnico" }).mockResolvedValueOnce({ estado: "ok", egreso: e, repetido: true })
  abrir(); completar()
  fireEvent.submit(screen.getByRole("form", { name: "Registrar gasto" }))
  await screen.findByText(/Conservamos tus datos/)
  expect(screen.queryByText(/Gasto registrado:/)).toBeNull()
  fireEvent.submit(screen.getByRole("form", { name: "Registrar gasto" }))
  await screen.findByText("Gasto registrado: Alquiler.")
  expect(registrar.mock.calls[0][0].claveSolicitud).toBe(registrar.mock.calls[1][0].claveSolicitud)
  expect(refresh).toHaveBeenCalledTimes(1)
  expect(screen.queryByRole("dialog")).toBeNull()
})
it("bloquea doble envio y cierre pendiente; Escape devuelve foco al cancelar", async () => {
  let resolver!: (r: unknown) => void
  registrar.mockImplementation(() => new Promise(r => { resolver = r }))
  abrir(); completar()
  const form = screen.getByRole("form", { name: "Registrar gasto" })
  fireEvent.submit(form); fireEvent.submit(form)
  expect(registrar).toHaveBeenCalledTimes(1)
  expect((screen.getByRole("button", { name: "Cancelar" }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" })
  expect(screen.getByRole("dialog")).toBeTruthy()
  await act(async () => resolver({ estado: "error_tecnico" }))
  fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" })
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull())
  await waitFor(() => expect(document.activeElement).toBe(screen.getByRole("button", { name: "Registrar gasto" })))
})
it("sesion vencida y conflicto conservan formulario sin exito", async () => {
  registrar.mockResolvedValueOnce({ estado: "sesion_requerida" }).mockResolvedValueOnce({ estado: "conflicto_solicitud" })
  abrir(); completar(); fireEvent.submit(screen.getByRole("form", { name: "Registrar gasto" }))
  expect(await screen.findByRole("link", { name: "Iniciar sesión" })).toBeTruthy()
  fireEvent.submit(screen.getByRole("form", { name: "Registrar gasto" }))
  expect(await screen.findByText(/Esta solicitud ya se usó/)).toBeTruthy()
  expect(refresh).not.toHaveBeenCalled()
})
it("detalle consulta, confirma anulacion, conserva historia e importe sin editar", async () => {
  detalle.mockResolvedValue({ estado: "ok", egreso: e })
  anular.mockResolvedValue({ estado: "ok", egreso: { ...e, estado: "ANULADO", anuladoEn: "2026-11-10T16:00:00Z" } })
  render(<EgresosAdmin egresos={[e]} filtros={filtros} />)
  fireEvent.click(screen.getByRole("button", { name: "Ver detalle de Alquiler" }))
  await screen.findByRole("region", { name: "Historial del gasto" })
  fireEvent.click(screen.getByRole("button", { name: "Anular gasto" }))
  expect(anular).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole("button", { name: "Confirmar anulación" }))
  await screen.findByText(/Gasto anulado. Se conserva/)
  const dialogo = screen.getByRole("dialog")
  expect(within(dialogo).getByText("Anulado")).toBeTruthy()
  expect(within(dialogo).getByText(/No integra los totales vigentes/)).toBeTruthy()
  expect(within(dialogo).queryByRole("button", { name: "Anular gasto" })).toBeNull()
})
it("error al consultar permite reintento, y anulacion fallida no inventa exito", async () => {
  detalle.mockResolvedValueOnce({ estado: "error_tecnico" }).mockResolvedValueOnce({ estado: "ok", egreso: e })
  anular.mockRejectedValue(Error("red"))
  render(<EgresosAdmin egresos={[e]} filtros={filtros} />)
  fireEvent.click(screen.getByRole("button", { name: "Ver detalle de Alquiler" }))
  fireEvent.click(await screen.findByRole("button", { name: "Reintentar consulta" }))
  fireEvent.click(await screen.findByRole("button", { name: "Anular gasto" }))
  fireEvent.click(screen.getByRole("button", { name: "Confirmar anulación" }))
  expect(await screen.findByText(/No pudimos anular el gasto/)).toBeTruthy()
  expect(refresh).not.toHaveBeenCalled()
})
